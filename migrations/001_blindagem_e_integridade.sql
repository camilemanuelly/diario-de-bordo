-- 6. Check Constraints e restrição de sobreposição operacional
ALTER TABLE public.perfis
  DROP CONSTRAINT IF EXISTS chk_perfis_dias_trabalho_range,
  ADD CONSTRAINT chk_perfis_dias_trabalho_range CHECK (dias_trabalho BETWEEN 1 AND 365),
  DROP CONSTRAINT IF EXISTS chk_perfis_dias_folga_range,
  ADD CONSTRAINT chk_perfis_dias_folga_range CHECK (dias_folga BETWEEN 1 AND 365),
  DROP CONSTRAINT IF EXISTS chk_perfis_posto_valido,
  ADD CONSTRAINT chk_perfis_posto_valido CHECK (
    posto IS NULL OR posto IN (
      'CFL', 'PLF', 'MFL', 'CMF', 'MFC', 'MAC',
      'SUF', 'CTF', 'MFM', 'MAM',
      'CZA', 'TAA'
    )
  );

ALTER TABLE public.escalas
  DROP CONSTRAINT IF EXISTS chk_escalas_datas_ordenadas,
  ADD CONSTRAINT chk_escalas_datas_ordenadas CHECK (data_fim >= data_inicio),
  DROP CONSTRAINT IF EXISTS chk_escalas_dias_totais_positivo,
  ADD CONSTRAINT chk_escalas_dias_totais_positivo CHECK (dias_totais > 0),
  DROP CONSTRAINT IF EXISTS chk_escalas_tipo_valido,
  ADD CONSTRAINT chk_escalas_tipo_valido CHECK (
    tipo IN ('Porto', 'Embarque', 'Folga', 'Atestado')
  );

-- Bloqueia sobreposição entre Porto, Embarque e Folga para o mesmo usuário;
-- Atestado fica fora do filtro para poder ocorrer em paralelo.
ALTER TABLE public.escalas
  DROP CONSTRAINT IF EXISTS excl_escalas_sem_sobreposicao_operacional,
  ADD CONSTRAINT excl_escalas_sem_sobreposicao_operacional
  EXCLUDE USING gist (
    user_id WITH =,
    daterange(data_inicio, data_fim, '[]') WITH &&
  )
  WHERE (tipo IN ('Porto', 'Embarque', 'Folga'));

-- 7. Funções e Triggers de integridade, timestamps, perfil automático e auditoria
CREATE OR REPLACE FUNCTION public.fn_escalas_calcula_dias_e_timestamp()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.user_id IS NULL THEN
    NEW.user_id := auth.uid();
  END IF;

  IF NEW.data_fim < NEW.data_inicio THEN
    RAISE EXCEPTION 'A data final (%) não pode ser anterior à data inicial (%).', NEW.data_fim, NEW.data_inicio;
  END IF;

  NEW.dias_totais := (NEW.data_fim - NEW.data_inicio) + 1;

  IF TG_OP = 'INSERT' THEN
    NEW.created_at := COALESCE(NEW.created_at, NOW());
    NEW.updated_at := NOW();
  ELSIF TG_OP = 'UPDATE' THEN
    NEW.created_at := OLD.created_at;
    NEW.updated_at := NOW();
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_escalas_calcula_dias_e_timestamp ON public.escalas;
CREATE TRIGGER trg_escalas_calcula_dias_e_timestamp
BEFORE INSERT OR UPDATE ON public.escalas
FOR EACH ROW
EXECUTE FUNCTION public.fn_escalas_calcula_dias_e_timestamp();

CREATE OR REPLACE FUNCTION public.fn_perfis_atualiza_timestamp()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.updated_at := NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_perfis_atualiza_timestamp ON public.perfis;
CREATE TRIGGER trg_perfis_atualiza_timestamp
BEFORE UPDATE ON public.perfis
FOR EACH ROW
EXECUTE FUNCTION public.fn_perfis_atualiza_timestamp();

CREATE OR REPLACE FUNCTION public.fn_criar_perfil_novo_usuario()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.perfis (id, nome_exibicao, empresa, dias_trabalho, dias_folga)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data ->> 'nome_exibicao', ''),
    'Atem',
    10,
    5
  )
  ON CONFLICT (id) DO NOTHING;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_auth_users_criar_perfil ON auth.users;
CREATE TRIGGER trg_auth_users_criar_perfil
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.fn_criar_perfil_novo_usuario();

CREATE OR REPLACE FUNCTION public.fn_auditar_exclusao_escala()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.escalas_auditoria_exclusao (
    escala_id,
    user_id,
    tipo,
    data_inicio,
    data_fim,
    dias_totais,
    observacao,
    criado_em,
    atualizado_em,
    excluido_em,
    excluido_por
  )
  VALUES (
    OLD.id,
    OLD.user_id,
    OLD.tipo,
    OLD.data_inicio,
    OLD.data_fim,
    OLD.dias_totais,
    OLD.observacao,
    OLD.created_at,
    OLD.updated_at,
    NOW(),
    auth.uid()
  );

  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_escalas_auditar_exclusao ON public.escalas;
CREATE TRIGGER trg_escalas_auditar_exclusao
AFTER DELETE ON public.escalas
FOR EACH ROW
EXECUTE FUNCTION public.fn_auditar_exclusao_escala();

